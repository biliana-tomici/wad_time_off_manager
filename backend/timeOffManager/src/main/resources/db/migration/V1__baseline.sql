CREATE TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    first_name VARCHAR(255),
    last_name VARCHAR(255),
    role VARCHAR(50) NOT NULL DEFAULT 'EMPLOYEE',
    manager_id BIGINT,
    CONSTRAINT fk_users_manager FOREIGN KEY (manager_id) REFERENCES users(id)
);

CREATE TABLE project (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    min_emp BIGINT,
    name VARCHAR(255),
    manager_id BIGINT,
    CONSTRAINT fk_project_manager FOREIGN KEY (manager_id) REFERENCES users(id)
);

CREATE TABLE balance (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255),
    days_left BIGINT,
    max_days BIGINT,
    version BIGINT NOT NULL DEFAULT 0,
    employee_id BIGINT,
    CONSTRAINT fk_balance_employee FOREIGN KEY (employee_id) REFERENCES users(id)
);

CREATE TABLE request (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_id BIGINT,
    balance_id BIGINT,
    start_date DATE,
    end_date DATE,
    explanation VARCHAR(255),
    status VARCHAR(50),
    creation_date DATE,
    modified_date DATE,
    decided_by BIGINT,
    decided_at TIMESTAMP,
    decision_comment VARCHAR(255),
    CONSTRAINT fk_request_employee FOREIGN KEY (employee_id) REFERENCES users(id),
    CONSTRAINT fk_request_balance FOREIGN KEY (balance_id) REFERENCES balance(id),
    CONSTRAINT fk_request_decided_by FOREIGN KEY (decided_by) REFERENCES users(id)
);

CREATE TABLE project_list (
    project_id BIGINT NOT NULL,
    employee_id BIGINT NOT NULL,
    CONSTRAINT pk_project_list PRIMARY KEY (project_id, employee_id),
    CONSTRAINT fk_project_list_project FOREIGN KEY (project_id) REFERENCES project(id),
    CONSTRAINT fk_project_list_employee FOREIGN KEY (employee_id) REFERENCES users(id)
);
